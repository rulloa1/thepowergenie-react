import { chromium } from 'playwright'
import { mkdir, writeFile } from 'node:fs/promises'
import assert from 'node:assert/strict'

const base = process.env.VIDEO_STUDIO_URL || 'http://localhost:3016'
await mkdir('.impeccable/review', { recursive: true })
const browser = await chromium.launch({ headless: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 1050 } })
const errors = []
page.on('pageerror', error => errors.push(error.message))
try {
  await page.goto(`${base}/video-studio`)
  await page.getByRole('heading', { name: 'From a spark to a short.' }).waitFor()
  await page.locator('.vs-frame img').evaluate(img => img.decode())
  await page.screenshot({ path: '.impeccable/review/desktop.png', fullPage: true })
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
  await page.getByRole('button', { name: 'Play preview', exact: true }).click()
  await page.waitForTimeout(650)
  assert.ok(Number(await page.getByRole('slider', { name: 'Preview position' }).inputValue()) > 0)
  await page.getByRole('button', { name: 'Pause preview', exact: true }).click()
  await page.getByRole('button', { name: /Edit scene 2/ }).click()
  assert.equal(await page.locator('.vs-preview-scene').innerText(), 'Scene 2 / 3')
  await page.getByRole('button', { name: 'Connections', exact: true }).click()
  await page.getByLabel('OpenAI API key').fill('test-session-key')
  await page.getByRole('button', { name: 'Save project', exact: true }).click()
  const stored = await page.evaluate(() => localStorage.getItem('powergenie.video-studio.v1'))
  assert.ok(!stored.includes('test-session-key'))
  await page.getByRole('button', { name: 'Close connections' }).click()
  await page.getByRole('tab', { name: 'Voiceover', exact: true }).click()
  await page.getByLabel('Write a separate narration script').check()
  await page.getByRole('textbox', { name: 'Narration', exact: true }).fill('An independently edited voiceover.')
  await page.getByRole('tab', { name: 'Export', exact: true }).click()
  await page.getByRole('button', { name: 'Render video', exact: true }).click()
  await page.getByRole('button', { name: 'Download video', exact: true }).waitFor({ timeout: 45000 })
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Download video', exact: true }).click()
  const download = await downloadPromise
  const videoPath = '.impeccable/review/video-studio-export.webm'
  await download.saveAs(videoPath)
  const output = await page.locator('.vs-output video').evaluate(async video => {
    await new Promise((resolve, reject) => { if (video.readyState >= 1) resolve(); else { video.onloadedmetadata = resolve; video.onerror = reject } })
    return { width: video.videoWidth, height: video.videoHeight, duration: video.duration }
  })
  assert.equal(output.width, 720); assert.equal(output.height, 1280)
  // MediaRecorder WebM can omit duration metadata; playback and decoded dimensions still prove a real video.
  await page.locator('.vs-output video').evaluate(video => video.play())
  await page.waitForTimeout(700)
  assert.ok(await page.locator('.vs-output video').evaluate(video => video.currentTime > 0))
  await page.locator('.vs-output video').evaluate(video => video.pause())
  await page.getByRole('button', { name: 'Load example', exact: true }).click()
  await page.getByRole('tab', { name: /Storyboard/ }).click()
  await page.setViewportSize({ width: 390, height: 844 })
  await page.evaluate(() => scrollTo(0, 0))
  await page.screenshot({ path: '.impeccable/review/mobile.png', fullPage: true })
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
  await page.getByRole('link', { name: 'Preview scene 1', exact: true }).click()
  assert.ok(await page.locator('#vs-preview').evaluate(element => element.getBoundingClientRect().top < 80))
  await page.getByRole('link', { name: 'Back to scene 1', exact: true }).click()
  assert.ok(await page.locator('#vs-scene-editor').evaluate(element => element.getBoundingClientRect().top < 80))
  await page.evaluate(() => scrollTo(0, 0))
  await page.getByRole('button', { name: 'Connections', exact: true }).click()
  await page.screenshot({ path: '.impeccable/review/mobile-connections.png', fullPage: true })
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
  await page.getByRole('button', { name: 'Close connections' }).click()
  await page.getByLabel('Creation mode').selectOption('local')
  await page.getByLabel('Video idea').fill('A rainy morning. Coffee by the window. A slower start.')
  await page.getByRole('button', { name: /Build storyboard/ }).click()
  await page.getByText('Local outline created.', { exact: false }).waitFor()
  assert.equal(await page.locator('.vs-scene-thumb').count(), 3)
  await page.getByRole('tab', { name: 'Export', exact: true }).click()
  assert.equal(await page.getByRole('button', { name: 'Render video', exact: true }).isDisabled(), true)
  await page.getByRole('button', { name: 'Load example', exact: true }).click()
  await page.getByRole('tab', { name: /Storyboard/ }).click()
  await page.getByLabel('Aspect ratio').selectOption('16:9')
  await page.getByRole('button', { name: 'Add scene', exact: true }).click()
  await page.getByRole('button', { name: 'Delete scene', exact: true }).click()
  assert.equal(await page.locator('.vs-scene-thumb').count(), 3)
  const noKey = await page.request.post(`${base}/api/video-studio`, { data: { action: 'plan' } })
  assert.equal(noKey.status(), 400)
  // Exercise the second composition path: an uploaded video plus decoded narration.
  await page.getByRole('button', { name: 'Load example', exact: true }).click()
  await page.getByLabel('Aspect ratio').selectOption('9:16')
  await page.getByRole('button', { name: /Edit scene 1/ }).click()
  await page.locator('input[type=file][accept^="image/jpeg"]').setInputFiles(videoPath)
  await page.getByRole('button', { name: 'Play preview', exact: true }).click()
  await page.waitForTimeout(500)
  assert.ok(await page.locator('.vs-frame video').evaluate(video => video.currentTime > 0))
  await page.getByRole('button', { name: 'Pause preview', exact: true }).click()
  await page.getByRole('tab', { name: 'Voiceover', exact: true }).click()
  const sampleRate = 22050
  const wav = Buffer.alloc(44 + sampleRate * 2)
  wav.write('RIFF', 0); wav.writeUInt32LE(wav.length - 8, 4); wav.write('WAVEfmt ', 8)
  wav.writeUInt32LE(16, 16); wav.writeUInt16LE(1, 20); wav.writeUInt16LE(1, 22)
  wav.writeUInt32LE(sampleRate, 24); wav.writeUInt32LE(sampleRate * 2, 28)
  wav.writeUInt16LE(2, 32); wav.writeUInt16LE(16, 34); wav.write('data', 36); wav.writeUInt32LE(sampleRate * 2, 40)
  for (let i = 0; i < sampleRate; i++) wav.writeInt16LE(Math.round(Math.sin(i / sampleRate * Math.PI * 2 * 440) * 5000), 44 + i * 2)
  await page.locator('input[type=file][accept^="audio/mpeg"]').setInputFiles({ name: 'test-narration.wav', mimeType: 'audio/wav', buffer: wav })
  await page.getByText('Narration attached.', { exact: true }).waitFor()
  await page.getByRole('tab', { name: 'Export', exact: true }).click()
  await page.getByRole('button', { name: 'Render video', exact: true }).click()
  await page.getByRole('button', { name: 'Download video', exact: true }).waitFor({ timeout: 45000 })
  const audioDownloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Download video', exact: true }).click()
  await (await audioDownloadPromise).saveAs('.impeccable/review/video-studio-with-audio.webm')
  assert.deepEqual(errors, [])
  await writeFile('.impeccable/review/video-studio-smoke.json', JSON.stringify({ passed: true, realExport: output, errors, checks: ['desktop', 'mobile', 'connections', 'keys not persisted', 'scene navigation', 'playback', 'narration editing', 'real video export and playback', 'local storyboard', 'incomplete export blocked', 'scene add/delete', 'aspect ratio', 'API validation', 'uploaded clip playback and export', 'uploaded narration and audio mixing'] }, null, 2))
  console.log(JSON.stringify({ passed: true, output, errors }))
} finally { await browser.close() }
